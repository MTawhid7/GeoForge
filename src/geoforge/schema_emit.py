"""Emit the JSON Schema document and the frontend's TypeScript types from `schema.py`.

The dataclasses are the definition; these are two views of it. Generating them means the
frontend cannot drift from what the pipeline emits, and the drift check turns that from a
convention into a build failure.

**Why a hand-written emitter and not `json-schema-to-typescript`.** It would put a Node
toolchain in the Python build's dependency path and a cross-language ordering constraint into
CI, for about a dozen types. Worse, its formatting churns with tool and prettier versions,
which is a direct hazard to a repo whose other artifacts are checked byte for byte — the drift
check would start failing on whitespace nobody chose. Walking `dataclasses.fields()` is smaller
than the configuration needed to drive the alternative.

Output is deterministic: fields in declaration order, no timestamps, no version stamps beyond
`SCHEMA_VERSION` itself. Two runs of `--emit` produce identical bytes, which is what lets
`--check` be a byte comparison rather than a semantic one.
"""

from __future__ import annotations

import argparse
import dataclasses
import difflib
import json
import sys
import types
import typing
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from geoforge import schema
from geoforge.schema import SCHEMA_VERSION

_ROOT = Path(__file__).resolve().parents[2]
TS_PATH = _ROOT / "web" / "src" / "types" / "generated" / "puzzle.ts"
JSON_SCHEMA_PATH = _ROOT / "banks" / "schema" / f"puzzle-{SCHEMA_VERSION}.schema.json"

_BANNER = "DO NOT EDIT — generated by `uv run python -m geoforge.schema_emit --emit`"

#: Emitted in dependency order, so the TypeScript reads top-down without forward references.
EXPORTED: tuple[type, ...] = (
    schema.DisplayPoint,
    schema.DisplayCircle,
    schema.AngleArc,
    schema.Marks,
    schema.Figure,
    schema.Quantity,
    schema.ExactValue,
    schema.Given,
    schema.GoalInput,
    schema.Goal,
    schema.Step,
    schema.Difficulty,
    schema.ReferencePoint,
    schema.ReferenceFigure,
    schema.Puzzle,
)

#: Keys `to_json` renames or synthesises, which `dataclasses.fields` cannot see. Kept as an
#: explicit table so a rename is a deliberate edit rather than a type the frontend quietly
#: disagrees with. `TestGeneratedTypesMatchTheJson` proves the table is complete against real
#: emitted payloads, which is the only thing that can catch an override nobody added.
_JSON_OVERRIDES: Mapping[type, Mapping[str, str]] = {
    schema.Goal: {"display": "__drop__", "answer": "ExactValue & { display: string }"},
}


def ts_type(annotation: Any) -> str:
    """Python annotation to TypeScript. Raises on anything it has not been taught."""
    if isinstance(annotation, str):
        annotation = getattr(schema, annotation, annotation)
    if annotation is str:
        return "string"
    if annotation is bool:
        return "boolean"
    if annotation in (int, float):
        return "number"
    if annotation is Any:
        return "unknown"
    if dataclasses.is_dataclass(annotation) and isinstance(annotation, type):
        return annotation.__name__

    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return " | ".join(json.dumps(a) for a in args)
    if origin in (Union, types.UnionType):
        return " | ".join(ts_type(a) for a in args if a is not type(None)) + (
            " | null" if type(None) in args else ""
        )
    if origin in (tuple, list, Sequence):
        if not args:
            return "unknown[]"
        if len(args) == 2 and args[1] is Ellipsis:
            return f"{ts_type(args[0])}[]"
        # A fixed-arity tuple keeps its arity: `at: tuple[str, str, str]` is (P, VERTEX, Q),
        # and rendering it as `string[]` would let the frontend index a fourth element.
        return f"[{', '.join(ts_type(a) for a in args)}]"
    if origin in (dict, Mapping):
        return (
            f"Record<{ts_type(args[0])}, {ts_type(args[1])}>" if args else "Record<string, unknown>"
        )
    raise TypeError(f"schema_emit has not been taught how to render {annotation!r} in TypeScript")


def json_type(annotation: Any) -> dict[str, Any]:
    """Python annotation to a JSON Schema fragment. Raises on anything it has not been taught."""
    if isinstance(annotation, str):
        annotation = getattr(schema, annotation, annotation)
    if annotation is str:
        return {"type": "string"}
    if annotation is bool:
        return {"type": "boolean"}
    if annotation is int:
        return {"type": "integer"}
    if annotation is float:
        return {"type": "number"}
    if annotation is Any:
        return {}
    if dataclasses.is_dataclass(annotation) and isinstance(annotation, type):
        return {"$ref": f"#/$defs/{annotation.__name__}"}

    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return {"enum": list(args)}
    if origin in (Union, types.UnionType):
        non_null = [json_type(a) for a in args if a is not type(None)]
        if type(None) in args:
            non_null.append({"type": "null"})
        return {"anyOf": non_null} if len(non_null) > 1 else non_null[0]
    if origin in (tuple, list, Sequence):
        if not args:
            return {"type": "array"}
        if len(args) == 2 and args[1] is Ellipsis:
            return {"type": "array", "items": json_type(args[0])}
        return {
            "type": "array",
            "prefixItems": [json_type(a) for a in args],
            "minItems": len(args),
            "maxItems": len(args),
        }
    if origin in (dict, Mapping):
        return {"type": "object"}
    raise TypeError(f"schema_emit has not been taught how to render {annotation!r} in JSON Schema")


def _fields(cls: type) -> list[tuple[str, Any, bool]]:
    """(name, annotation, required) for one dataclass, in declaration order."""
    hints = typing.get_type_hints(cls)
    out = []
    for f in dataclasses.fields(cls):
        required = f.default is dataclasses.MISSING and f.default_factory is dataclasses.MISSING
        out.append((f.name, hints[f.name], required))
    return out


def emit_ts() -> str:
    lines = [
        "// " + _BANNER,
        "//",
        "// Puzzle JSON v" + SCHEMA_VERSION + ". The Python dataclasses in",
        "// src/geoforge/schema.py are the definition; this file is a view of them.",
        "",
        f'export const SCHEMA_VERSION = "{SCHEMA_VERSION}";',
        "",
    ]
    for cls in EXPORTED:
        overrides = _JSON_OVERRIDES.get(cls, {})
        lines.append(f"export interface {cls.__name__} {{")
        for name, annotation, required in _fields(cls):
            override = overrides.get(name)
            if override == "__drop__":
                continue
            rendered = override or ts_type(annotation)
            lines.append(f"  {name}{'' if required else '?'}: {rendered};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def json_schema() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for cls in EXPORTED:
        overrides = _JSON_OVERRIDES.get(cls, {})
        properties: dict[str, Any] = {}
        required: list[str] = []
        for name, annotation, is_required in _fields(cls):
            if overrides.get(name) == "__drop__":
                continue
            if name in overrides:
                properties[name] = {"$ref": "#/$defs/ExactValue"}
            else:
                properties[name] = json_type(annotation)
            if is_required:
                required.append(name)
        defs[cls.__name__] = {
            "type": "object",
            "properties": properties,
            "required": required,
            "additionalProperties": False,
        }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://geoforge.dev/schema/puzzle-{SCHEMA_VERSION}.json",
        "title": f"GeoForge puzzle v{SCHEMA_VERSION}",
        "description": _BANNER,
        "$ref": "#/$defs/Puzzle",
        "$defs": defs,
    }


def json_schema_text() -> str:
    return json.dumps(json_schema(), indent=2, sort_keys=True) + "\n"


def _artifacts() -> tuple[tuple[Path, str], ...]:
    return ((TS_PATH, emit_ts()), (JSON_SCHEMA_PATH, json_schema_text()))


def write() -> list[Path]:
    written = []
    for path, text in _artifacts():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        written.append(path)
    return written


def check() -> list[str]:
    """Byte-compare the committed artifacts against a fresh render. Empty means no drift."""
    problems = []
    for path, expected in _artifacts():
        actual = path.read_text() if path.exists() else ""
        if actual != expected:
            rel = path.relative_to(_ROOT) if path.is_relative_to(_ROOT) else path
            diff = "\n".join(
                difflib.unified_diff(
                    actual.splitlines(),
                    expected.splitlines(),
                    f"{rel} (committed)",
                    f"{rel} (fresh)",
                    lineterm="",
                )
            )
            problems.append(f"{rel} is stale:\n{diff}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Emit or check the generated schema artifacts.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--emit", action="store_true", help="write the artifacts")
    group.add_argument("--check", action="store_true", help="fail if they are stale")
    args = parser.parse_args(argv)

    if args.emit:
        for path in write():
            print(f"wrote {path.relative_to(_ROOT) if path.is_relative_to(_ROOT) else path}")
        return 0

    problems = check()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            "\nRun `uv run python -m geoforge.schema_emit --emit` and commit the result.",
            file=sys.stderr,
        )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
